// Kullanım: node tools/dev/item-protocol-test.mjs <port>  (yeni eşya mesajları: gull/parrot/loot iletimi ve doğrulama)
import WebSocket from 'ws';
const port = process.argv[2];
const mk = (q = 'create=1') => new Promise((res) => { const ws = new WebSocket(`ws://localhost:${port}/ws?${q}`); ws.msgs = []; ws.on('message', (d) => ws.msgs.push(JSON.parse(d))); ws.on('open', () => res(ws)); });
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
const last = (ws, t) => [...ws.msgs].reverse().find((m) => m.type === t);
const a = await mk();
a.send(JSON.stringify({ type: 'create', name: 'A', character: 'fox' }));
await sleep(200);
const code = last(a, 'room').code;
const b = await mk(`c=${code}`);
b.send(JSON.stringify({ type: 'join', code, name: 'B', character: 'panda' }));
await sleep(200);
b.send(JSON.stringify({ type: 'ready', ready: true })); await sleep(150);
a.send(JSON.stringify({ type: 'start', trackCount: 600 })); await sleep(700);
const idA = last(a, 'welcome').id;
const idB = last(b, 'welcome').id;
const items = (ws) => ws.msgs.filter((m) => m.type === 'item');
a.send(JSON.stringify({ type: 'item', kind: 'gull', id: `${idA}:1`, owner: idA, target: idB })); await sleep(900);
console.log('1 gull → B alır', JSON.stringify(items(b).at(-1)));
a.send(JSON.stringify({ type: 'item', kind: 'parrot', id: `${idA}:2`, owner: idA, target: idB })); await sleep(900);
console.log('2 parrot → B alır', JSON.stringify(items(b).at(-1)));
a.send(JSON.stringify({ type: 'item', kind: 'elephant', id: `${idA}:3`, owner: idA })); await sleep(900);
console.log('3 elephant artık yok → B yeni mesaj almaz, son hâlâ parrot:', items(b).at(-1)?.kind);
b.send(JSON.stringify({ type: 'item', kind: 'loot', id: `${idB}:1`, owner: idB, to: idA, item: 'coconut', uses: 2 })); await sleep(900);
console.log('4 loot → A alır', JSON.stringify(items(a).at(-1)));
b.send(JSON.stringify({ type: 'item', kind: 'loot', id: `${idB}:2`, owner: idB, to: idA, item: 'hack<x>', uses: 9 })); await sleep(900);
console.log('5 geçersiz eşya → null/1', JSON.stringify(items(a).at(-1)));
a.send(JSON.stringify({ type: 'item', kind: 'loot', id: `${idB}:3`, owner: idB, to: idA, item: 'oil' })); await sleep(900);
console.log('6 başkası adına loot reddedilir (A\'da yeni mesaj yok)', items(a).length);
process.exit(0);
