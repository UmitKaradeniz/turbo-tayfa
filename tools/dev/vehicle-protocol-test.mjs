// Kullanım: node tools/dev/vehicle-protocol-test.mjs <port>  (Node sunucusu ya da `wrangler dev` portu; ?create=1 / ?c=KOD sorgusu iki ortamda da çalışır)
import WebSocket from 'ws';
const port = process.argv[2];
const mk = (q = 'create=1') => new Promise((res) => { const ws = new WebSocket(`ws://localhost:${port}/ws?${q}`); ws.msgs = []; ws.on('message', (d) => ws.msgs.push(JSON.parse(d))); ws.on('open', () => res(ws)); });
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
const last = (ws, t) => [...ws.msgs].reverse().find((m) => m.type === t);
const a = await mk();
a.send(JSON.stringify({ type: 'create', name: 'A', character: 'fox', vehicle: 'heavy' }));
await sleep(200);
const code = last(a, 'room').code;
const b = await mk(`c=${code}`);
b.send(JSON.stringify({ type: 'join', code, name: 'B', character: 'panda' }));
await sleep(200);
let pl = last(a, 'room').players; console.log('1', pl.map((p) => `${p.character}:${p.vehicle}`).join(' '));
b.send(JSON.stringify({ type: 'vehicle', vehicle: 'rocket' })); await sleep(150);
pl = last(a, 'room').players; console.log('2', pl.map((p) => `${p.character}:${p.vehicle}`).join(' '));
b.send(JSON.stringify({ type: 'vehicle', vehicle: 'hack<script>' })); await sleep(150);
pl = last(a, 'room').players; console.log('3 invalid→', pl.map((p) => `${p.character}:${p.vehicle}`).join(' '));
b.send(JSON.stringify({ type: 'vehicle', vehicle: 'agile' })); await sleep(150);
b.send(JSON.stringify({ type: 'ready', ready: true })); await sleep(150);
a.send(JSON.stringify({ type: 'start', trackCount: 600 })); await sleep(600);
const st = last(a, 'start'); console.log('4 entrants', st ? st.entrants.filter((e) => !e.bot).map((e) => `${e.character}:${e.vehicle}`).join(' ') + ' bots:' + st.entrants.filter((e) => e.bot).length + ' botVeh:' + st.entrants.filter((e) => e.bot).every((e) => e.vehicle === undefined) : 'no start');
process.exit(0);
